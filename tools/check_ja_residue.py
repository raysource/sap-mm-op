PUNCT = ["；", "，"]
CN_FUNC = set("这的了们为说时个发后从里么你我她它请谢吗呢吧着过还就都也很对给让")
CJK = re.compile(r"[\u4e00-\u9fff]{6,}")
KANA = re.compile(r"[\u3040-\u30ff]")

bad = 0
for f in sorted(glob.glob(os.path.join(ROOT, "ja", "*.html"))):
    with open(f, encoding="utf-8") as fh:
        s = fh.read()
    name = os.path.basename(f)
    for ch in PUNCT:
        if ch in s:
            print("%s 中文標点 %r x%d" % (name, ch, s.count(ch)))
            bad += 1
    hits = {}
    for ch in s:
        if ch in SIMP:
            hits[ch] = hits.get(ch, 0) + 1
    if hits:
        print("%s 簡体字 %s" % (name, hits))
        bad += 1
    sus = [r for r in CJK.findall(s) if not KANA.search(r) and (set(r) & CN_FUNC)]
    if sus:
        print("%s 中文らしき文: %s" % (name, sorted(set(sus))[:8]))
        bad += 1
print("OK: /ja/ に中文残存なし" if not bad else "NG: %d 件" % bad)
